import { mount, flushPromises } from '@vue/test-utils'
import { describe, beforeEach, it, expect, vi } from 'vitest'
import UserModelBansModal from '../UserModelBansModal.vue'
const api = vi.hoisted(() => ({ get: vi.fn(), replace: vi.fn(), clear: vi.fn(), history: vi.fn(), version: vi.fn(), catalog: vi.fn(), evaluate: vi.fn() }))
vi.mock('@/api/admin/modelRestrictions', () => ({ default: api, catalog: api.catalog, evaluate: api.evaluate }))
vi.mock('vue-i18n', async () => ({ ...await vi.importActual<typeof import('vue-i18n')>('vue-i18n'), useI18n: () => ({ t: (key: string) => key }) }))
vi.mock('@/stores/app', () => ({ useAppStore: () => ({ showSuccess: vi.fn() }) }))
const snapshot = () => ({ user_id: 42, revision: 3, updated_at: '', updated_by: 1, rules: [{ namespace: 'openai', canonical_model: 'gpt-5', enabled: true, expires_at: null, reason: 'manual', created_by: 1 }] })
function create() { return mount(UserModelBansModal, { props: { show: true, user: { id: 42, email: 'test@example.com' } }, global: { stubs: { teleport: true } } }) }
describe('UserModelBansModal', () => {
  beforeEach(() => { vi.resetAllMocks(); api.catalog.mockResolvedValue({ models: [] }); api.get.mockResolvedValue(snapshot()); api.replace.mockResolvedValue({ ...snapshot(), revision: 4 }) })
  it('evaluates with the selected alias context and clears context on a user switch', async () => {
    api.evaluate.mockResolvedValue({ status: 'allowed' })
    const wrapper = create(); await flushPromises()
    const form = wrapper.find('form')
    await form.find('input[maxlength="255"]').setValue('shared-alias')
    const inputs = form.findAll('details input')
    for (const [index, value] of ['openai', 'openai', 'responses', 'tool', 'provider-a'].entries()) await inputs[index].setValue(value)
    await form.trigger('submit'); await flushPromises()
    expect(api.evaluate).toHaveBeenCalledWith(42, [{ namespace: 'openai', transport: 'openai', protocol: 'responses', role: 'tool', provider_context: 'provider-a', model: 'shared-alias' }])
    await wrapper.setProps({ user: { id: 43, email: 'other@example.com' } }); await flushPromises()
    expect((wrapper.find('form details input').element as HTMLInputElement).value).toBe('')
    wrapper.unmount()
  })
  it('saves with the loaded revision and excludes server-owned actor fields', async () => {
    const wrapper = create(); await flushPromises()
    await wrapper.find('input[maxlength="2000"]').setValue('policy change')
    const save = wrapper.findAll('button').find(button => button.text() === 'common.save')!
    await save.trigger('click'); await flushPromises()
    expect(api.replace).toHaveBeenCalledWith(42, 3, [{ namespace: 'openai', canonical_model: 'gpt-5', enabled: true, expires_at: null, reason: 'manual' }], 'policy change')
    wrapper.unmount()
  })
  it('retains edits and shows a conflict when a concurrent writer wins', async () => {
    api.replace.mockRejectedValue({ response: { status: 409 } })
    const wrapper = create(); await flushPromises()
    await wrapper.find('input[maxlength="2000"]').setValue('policy change')
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click'); await flushPromises()
    expect(wrapper.find('[role="alert"]').text()).toBe('admin.modelBans.conflict')
    expect(api.replace).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })
  it('keeps a conflicting draft until a confirmed reload and requires a new change reason', async () => {
    api.replace.mockRejectedValue({ response: { status: 409 } })
    const wrapper = create(); await flushPromises()
    api.get.mockResolvedValueOnce({ ...snapshot(), revision: 8, rules: [{ ...snapshot().rules[0], reason: 'other administrator' }] })
    await wrapper.find('input[maxlength="2000"]').setValue('my draft reason')
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click'); await flushPromises()
    expect((wrapper.find('input[maxlength="2000"]').element as HTMLInputElement).value).toBe('my draft reason')
    expect(wrapper.findAll('button').find(button => button.text() === 'common.save')!.attributes('disabled')).toBeDefined()
    await wrapper.findAll('button').find(button => button.text() === 'admin.modelBans.reloadLatest')!.trigger('click'); await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === 'common.confirm')!.trigger('click'); await flushPromises()
    expect((wrapper.find('input[maxlength="2000"]').element as HTMLInputElement).value).toBe('')
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click'); await flushPromises()
    expect(api.replace).toHaveBeenCalledTimes(1)
    wrapper.unmount()
  })
  it('ignores a previous user load that resolves after the selected user changes', async () => {
    let resolveFirst!: (value: unknown) => void
    api.get.mockImplementationOnce(() => new Promise(resolve => { resolveFirst = resolve }))
    const wrapper = create()
    api.get.mockResolvedValueOnce({ ...snapshot(), user_id: 43, revision: 8 })
    await wrapper.setProps({ user: { id: 43, email: 'other@example.com' } }); await flushPromises()
    resolveFirst(snapshot()); await flushPromises()
    await wrapper.find('input[maxlength="2000"]').setValue('policy change')
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click'); await flushPromises()
    expect(api.replace.mock.calls[0].slice(0, 2)).toEqual([43, 8])
    wrapper.unmount()
  })
  it('does not replace a new user policy with an earlier save response', async () => {
    let resolveSave!: (value: unknown) => void
    api.replace.mockImplementationOnce(() => new Promise(resolve => { resolveSave = resolve }))
    const wrapper = create(); await flushPromises()
    await wrapper.find('input[maxlength="2000"]').setValue('policy change')
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click')
    api.get.mockResolvedValueOnce({ ...snapshot(), user_id: 43, revision: 8 })
    await wrapper.setProps({ user: { id: 43, email: 'other@example.com' } }); await flushPromises()
    await wrapper.find('input[maxlength="2000"]').setValue('policy change')
    resolveSave({ ...snapshot(), revision: 4 }); await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === 'common.save')!.trigger('click'); await flushPromises()
    expect(api.replace.mock.calls[1].slice(0, 2)).toEqual([43, 8])
    expect(wrapper.emitted('success')).toHaveLength(1)
    wrapper.unmount()
  })

})
