-- 原厂身份与传输平台分离。每个目录版本不可变；管理员更新仅推进 head。
CREATE TABLE IF NOT EXISTS model_identity_catalog_versions (
    revision BIGINT PRIMARY KEY CHECK (revision >= 1),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_by BIGINT NULL
);
CREATE TABLE IF NOT EXISTS model_identity_catalog_heads (
    id SMALLINT PRIMARY KEY CHECK (id = 1),
    revision BIGINT NOT NULL REFERENCES model_identity_catalog_versions(revision),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_by BIGINT NULL
);
CREATE TABLE IF NOT EXISTS model_identity_catalog_models (
    revision BIGINT NOT NULL REFERENCES model_identity_catalog_versions(revision),
    namespace VARCHAR(64) NOT NULL,
    canonical_model VARCHAR(255) NOT NULL,
    display_name VARCHAR(255) NOT NULL,
    source VARCHAR(500) NOT NULL,
    PRIMARY KEY (revision, namespace, canonical_model)
);
CREATE TABLE IF NOT EXISTS model_identity_catalog_aliases (
    revision BIGINT NOT NULL,
    namespace VARCHAR(64) NOT NULL,
    transport VARCHAR(64) NOT NULL DEFAULT '',
    alias VARCHAR(255) NOT NULL,
    canonical_model VARCHAR(255) NOT NULL,
    PRIMARY KEY (revision, namespace, transport, alias),
    FOREIGN KEY (revision, namespace, canonical_model)
        REFERENCES model_identity_catalog_models(revision, namespace, canonical_model)
);
